def is_hill_number(n):
    digits = str(num)
    i = 0
    l = len(digits)

    while i + 1 < l and digits[i] < digits[i+1]:
        i = i + 1

    if i == 0 or i == l - 1:
        return False

    while i + 1 < l and digits[i] > digits[i+1]:
        i = i + 1

    return i == l - 1


